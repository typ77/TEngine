        public ScriptGenerator(string inputPath, TableDefinition tableDef,
                               List<FieldSharedCacheInfo> sharedCacheInfos)
            : this(inputPath, tableDef.ClassName, ConvertToConfigDataList(tableDef.Rows, tableDef.PrimaryKey?.Type?.PrimitiveName ?? "int"),
                   sharedCacheInfos, tableDef.PrimaryKey?.Type?.PrimitiveName ?? "int",
                   tableDef.CompoundIndexes)
        {
        }

        private static List<ConfigData[]> ConvertToConfigDataList(List<TableRow> rows, string primaryKeyType)
        {
            var result = new List<ConfigData[]>();
            foreach (var row in rows)
            {
                var configs = new List<ConfigData>();
                // 首先添加主键
                configs.Add(new ConfigData
                {
                    Type = primaryKeyType,
                    Name = "Id",
                    Data = row.PrimaryKey
                });
                // 添加其余字段
                foreach (var (fieldName, fieldValue) in row.Fields)
                {
                    configs.Add(new ConfigData
                    {
                        Type = fieldValue.TypeDescriptor?.PrimitiveName ?? "str",
                        Name = fieldName,
                        Data = fieldValue.RawText
                    });
                }
                result.Add(configs.ToArray());
            }
            return result;
        }

        public string CreateCodeV2(string templateContent)
        {
            // 1. Process key type (##TKey##)
            string tKey = ReadExcel.GetTrueType(_idType);

            // 2. Generate struct variables for ##ClassName##Item (##StructVariables##)
            StringBuilder structVariables = new StringBuilder();
            if (_configDataList != null && _configDataList.Count > 0)
            {
                foreach (var data in _configDataList[0])
                {
                    structVariables.Append(PropertyString(data.Type, data.Name));
                }
            }

            // 3. Generate data reading code for item constructor (##ReadData##)
            StringBuilder readData = new StringBuilder();
            if (_configDataList != null && _configDataList.Count > 0)
            {
                // Read basic variables
                for (int i = 0; i < _configDataList[0].Length; i++)
                {
                    var data = _configDataList[0][i];
                    readData.Append(GetContainerString(data.Type, data.Name, container: false));
                }
                // Read container variables (lists/dictionaries)
                for (int i = 0; i < _configDataList[0].Length; i++)
                {
                    var data = _configDataList[0][i];
                    readData.Append(GetContainerString(data.Type, data.Name, container: true));
                }
            }

            // 4. Generate shared cache fields for config class (##SharedCacheFields##)
            StringBuilder sharedCacheFields = new StringBuilder();
            // 5. Generate shared cache initialization code (##InitSharedCache##)
            StringBuilder initSharedCache = new StringBuilder();
            // 6. Generate ReadHead method if needed (##ReadHeadDeclaration##)
            string readHeadDeclaration = string.Empty;

            int enabledCacheCount = 0;
            if (_sharedCacheInfos != null)
            {
                foreach (var cacheInfo in _sharedCacheInfos)
                {
                    if (!cacheInfo.EnableSharedCache)
                        continue;

                    enabledCacheCount++;
                    string fieldNameLower = cacheInfo.FieldName.ToLower();
                    string actualTypeName = ReadExcel.GetTrueType(cacheInfo.FieldType);

                    if (cacheInfo.FieldType == SupportType.String || cacheInfo.FieldType == SupportType.StringFull)
                    {
                        // String shared cache
                        sharedCacheFields.AppendLine($"\t\tinternal static Dictionary<int, string> _{fieldNameLower}SharedCache;");
                    }
                    else
                    {
                        // List/Dictionary/Object shared cache
                        sharedCacheFields.AppendLine($"\t\tinternal static Dictionary<int, {actualTypeName}> _{fieldNameLower}SharedCache;");
                    }

                    // Add initialization code (will be called during ReadHead)
                    // 二进制顺序：字段名 -> 缓存数量 -> 每个值
                    initSharedCache.AppendLine($"\t\t\t// 读取共享缓存: {cacheInfo.FieldName}");
                    initSharedCache.AppendLine($"\t\t\t_ = byteBuf.ReadString(); // 跳过字段名");
                    initSharedCache.AppendLine($"\t\t\tint {fieldNameLower}Count = byteBuf.ReadInt();");
                    // 预分配容量，避免填充时 Dictionary 逐步 resize（减少 GC 与 rehash 复制）
                    if (cacheInfo.FieldType == SupportType.String || cacheInfo.FieldType == SupportType.StringFull)
                    {
                        initSharedCache.AppendLine($"\t\t\t_{fieldNameLower}SharedCache = new Dictionary<int, string>({fieldNameLower}Count);");
                    }
                    else
                    {
                        initSharedCache.AppendLine($"\t\t\t_{fieldNameLower}SharedCache = new Dictionary<int, {actualTypeName}>({fieldNameLower}Count);");
                    }
                    initSharedCache.AppendLine($"\t\t\tfor (int i = 0; i < {fieldNameLower}Count; i++)");
                    initSharedCache.AppendLine($"\t\t\t{{");
                    if (cacheInfo.FieldType == SupportType.String || cacheInfo.FieldType == SupportType.StringFull)
                    {
                        initSharedCache.AppendLine($"\t\t\t\tstring value = byteBuf.ReadString();");
                    }
                    else
                    {
                        // index 从 1 开始，避免和外层循环变量 i 冲突
                        string deserializeCode = PropertyDeserialize(cacheInfo.FieldType, "value", 1);
                        initSharedCache.AppendLine($"\t\t\t\t{actualTypeName} value = {deserializeCode};");
                    }
                    initSharedCache.AppendLine($"\t\t\t\t_{fieldNameLower}SharedCache[i] = value;");
                    initSharedCache.AppendLine($"\t\t\t}}");
                }
            }

            // 8. Generate compound index members (##CompoundIndexMembers##)
            string compoundIndexMembers = GenerateCompoundIndexCode();
            string compoundIndexBuildCalls = GenerateCompoundIndexBuildCalls();

            // 有共享缓存 或 有组合索引 时，生成 override ReadHead
            if (enabledCacheCount > 0 || HasCompoundIndex)
            {
                string preBase = enabledCacheCount > 0
                    ? "\t\t\t_ = byteBuf.ReadInt(); // 跳过统计有多少个字段启用了共享缓存\n##InitSharedCache##\n"
                    : "";
                string postBase = HasCompoundIndex ? "\n" + compoundIndexBuildCalls : "";

                readHeadDeclaration =
@"        protected override void ReadHead(ByteBuf byteBuf)
        {
" + preBase + @"            base.ReadHead(byteBuf);" + postBase + @"
        }
";
            }

            // 6. Generate key reading code (##ReadKey##)
            string readKey = $"\t\t\treturn {PropertyDeserialize(_idType)};";

            // 7. Generate item creation code (##ReadItem##)
            string readItem = $"\t\t\treturn new {_className}Item(byteBuf);";

            // Replace all placeholders in the template
            // 如果有共享缓存才插入 ReadHead 声明，否则保持模板原样（不包含 ReadHead）
            if (!string.IsNullOrEmpty(readHeadDeclaration))
            {
                readHeadDeclaration = readHeadDeclaration.Replace("##InitSharedCache##", initSharedCache.ToString());
            }

            var code = templateContent
                .Replace("##ClassName##", _className)
                .Replace("##StructVariables##", structVariables.ToString())
                .Replace("##ReadData##", readData.ToString())
                .Replace("##SharedCacheFields##", sharedCacheFields.ToString())
                .Replace("##CompoundIndexMembers##", compoundIndexMembers)
                .Replace("##ReadHeadDeclaration##", readHeadDeclaration)
                .Replace("##TKey##", tKey)
                .Replace("##ReadKey##", readKey)
                .Replace("##ReadItem##", readItem)
                .Replace("##fileName##", _className);

            return "// " + GeneratedCodeMarker + "\n" + code;
        }

        /// <summary>
        /// 生成无共享缓存版本的 Item + Config 类文本（用于 Editor 报告工具，不入运行时程序集）。
        /// 返回裸类文本（不含 namespace 包裹），由调用方负责包 namespace TEngine { ... }。
        /// </summary>
        public string GetUncompressedClasses()
        {
            return BuildUncompressedItemText() + BuildUncompressedConfigText();
        }

        /// <summary>
        /// 生成无共享缓存版本的 Item 类文本（读取完整值，不读索引）。
        /// 与现有 Item 类同表同结构，仅字段读取方式不同：所有字段强制走非共享分支。
        /// 用于报告工具加载 useSharedCache=false 导出的 bytes 做内存对比。
        /// </summary>
        internal string BuildUncompressedItemText()
        {
            var structVariables = new StringBuilder();
            var readData = new StringBuilder();
            if (_configDataList != null && _configDataList.Count > 0)
            {
                // 字段声明：复用 PropertyString，但临时禁用共享缓存查询
                using (SharedCacheScope.Disable(this))
                {
                    foreach (var data in _configDataList[0])
                        structVariables.Append(PropertyString(data.Type, data.Name));

                    for (int i = 0; i < _configDataList[0].Length; i++)
                        readData.Append(GetContainerString(_configDataList[0][i].Type, _configDataList[0][i].Name, container: false));
                    for (int i = 0; i < _configDataList[0].Length; i++)
                        readData.Append(GetContainerString(_configDataList[0][i].Type, _configDataList[0][i].Name, container: true));
                }
            }

            return $@"
		[Preserve]
		public class {_className}ItemUncompressed
		{{
{structVariables}
			public {_className}ItemUncompressed (ByteBuf byteBuf)
			{{
{readData}
			}}
		}}
";
        }

        /// <summary>
        /// 生成无共享缓存版本的 Config 类文本。
        /// ReadHead 不读共享缓存前缀（直接 base.ReadHead），但仍处理组合索引。
        /// </summary>
        internal string BuildUncompressedConfigText()
        {
            // 关键：必须在 SharedCacheScope.Disable 内生成，因为 GenerateCompoundIndexCode
            // 内部（ScriptGenerator.cs:436）对"共享 string 组合索引成员"会生成查 _xxxSharedCache
            // 的代码——而无缓存 Config 类没有 _xxxSharedCache 字段，会编译失败。
            // Disable 后 IsSharedCacheEnabled 返回 false，组合索引走非共享分支（直接 peek string 值）。
            using (SharedCacheScope.Disable(this))
            {
                string tKey = ReadExcel.GetTrueType(_idType);
                string readKey = $"\t\t\treturn {PropertyDeserialize(_idType)};";
                string readItem = $"\t\t\treturn new {_className}ItemUncompressed(byteBuf);";

                // 无共享缓存：ReadHead 仅在有组合索引时才 override（只调 base + 组合索引构建）
                string readHeadDeclaration = string.Empty;
                if (HasCompoundIndex)
                {
                    string compoundIndexBuildCalls = GenerateCompoundIndexBuildCalls();
                    readHeadDeclaration =
@"        protected override void ReadHead(ByteBuf byteBuf)
        {
            base.ReadHead(byteBuf);
" + compoundIndexBuildCalls + @"
        }
";
                }

                // 组合索引成员声明：组合索引字段/方法都是 instance 级（m_compoundIndex_{group} 是
                // instance 字段，BuildCompoundIndex_{group} 是 instance 方法），与 XxxConfig 不冲突，
                // 两类各自独立声明。但必须在 Disable 作用域内生成，避免引用 _xxxSharedCache。
                string compoundIndexMembers = GenerateCompoundIndexCode();

                return $@"
		[Preserve]
		public class {_className}ConfigUncompressed : TableBaseTemp<{tKey}, {_className}ItemUncompressed>
		{{
{compoundIndexMembers}
{readHeadDeclaration}
		    protected override {tKey} ReadKey(ByteBuf byteBuf)
		    {{
{readKey}
		    }}
        protected override {_className}ItemUncompressed CreateItem(ByteBuf byteBuf)
        {{
{readItem}
        }}
		}}
";
            }
        }

        /// <summary>
        /// 临时禁用共享缓存查询的作用域。using 块结束时恢复原值。
        /// </summary>
        private readonly struct SharedCacheScope : IDisposable
        {
            private readonly ScriptGenerator _gen;
            private readonly bool _prev;

            private SharedCacheScope(ScriptGenerator gen)
            {
                _gen = gen;
                _prev = gen._sharedCacheEnabled;
                gen._sharedCacheEnabled = false;
            }

            public static SharedCacheScope Disable(ScriptGenerator gen) => new SharedCacheScope(gen);

            public void Dispose() => _gen._sharedCacheEnabled = _prev;
        }

        private static string PropertyDeserialize(string type, string propertyName = "", int index = 0)
        {
            if (string.IsNullOrEmpty(type))
                return string.Empty;
            switch (type)
            {
                case SupportType.Bool:
                    return "byteBuf.ReadBool()";
                case SupportType.Int:
                case SupportType.LanguageType:
                    return "byteBuf.ReadInt()";
                case SupportType.UInt:
                    return "(uint)byteBuf.ReadInt()";
                case SupportType.ULong:
                    return "(ulong)byteBuf.ReadLong()";
                case SupportType.Short:
                    return "byteBuf.ReadShort()";
                case SupportType.Long:
                    return "byteBuf.ReadLong()";
                case SupportType.Float:
                    return "byteBuf.ReadFloat()";
                case SupportType.Double:
                    return "byteBuf.ReadDouble()";
                case SupportType.String:
                case SupportType.StringFull:
                    return "byteBuf.ReadString()";
                case SupportType.Vector2:
                case SupportType.Vector2Full:
                    return "byteBuf.ReadVector2()";
                case SupportType.Vector3:
                case SupportType.Vector3Full:
                    return "byteBuf.ReadVector3()";
                case SupportType.Vector4:
                case SupportType.Vector4Full:
                    return "byteBuf.ReadVector4()";
                case SupportType.Quaternion:
                case SupportType.QuaternionFull:
                    return "byteBuf.ReadQuaternion()";
                default:
                {
                    if (string.Equals(type, SupportType.RewardObject, StringComparison.OrdinalIgnoreCase))
                    {
                        return $"new RewardObject(byteBuf);";
                    }
                    if (string.Equals(type, SupportType.ConditionObject, StringComparison.OrdinalIgnoreCase))
                    {
                        return $"new ConditionObject(byteBuf);";
                    }
                    if (string.Equals(type, SupportType.EffectCfgObject, StringComparison.OrdinalIgnoreCase))
                    {
                        return $"new EffectCfgObject(byteBuf);";
                    }
                    if (string.Equals(type, SupportType.GradedPriceObject, StringComparison.OrdinalIgnoreCase))
                    {
                        return $"new GradedPriceObject(byteBuf);";
                    }
                    if (type.StartsWith(SupportType.List, StringComparison.OrdinalIgnoreCase) && type.EndsWith(">"))
                    {
                        string innerType = type.Substring(5, type.Length - 6);
                        var newType = ReadExcel.GetTrueType(type);
                        var sbProperty = new StringBuilder();
                        sbProperty.Append($"new {newType}();");
                        sbProperty.Append($"var n{index} = Math.Min(byteBuf.ReadSize(), byteBuf.Size);");
                        sbProperty.Append($"for (var i{index} = 0; i{index} < n{index}; i{index}++){{");
                        sbProperty.Append($"var item{index}={PropertyDeserialize(innerType, $"item{index}",index+1)};");
                        sbProperty.Append($"{propertyName}.Add(item{index});}}");
                        return sbProperty.ToString();
                    }
                    else if ((type.StartsWith(SupportType.Dictionary, StringComparison.OrdinalIgnoreCase) || type.StartsWith(SupportType.DictionaryFull, StringComparison.OrdinalIgnoreCase)) && type.EndsWith(">"))
                    {
                        var sbProperty = new StringBuilder();
                        var newType = ReadExcel.GetTrueType(type);
                        string keyType = null;
                        int commaIndex = type.IndexOf(',');
                        if (type.StartsWith(SupportType.Dictionary))
                        {
                            keyType = type.Substring(5, commaIndex - 5);
                        }
                        else if(type.StartsWith(SupportType.DictionaryFull))
                        {
                            keyType = type.Substring(11, commaIndex - 11);
                        }
                        string valueType = type.Substring(commaIndex + 1, type.Length - commaIndex - 2);
                        sbProperty.Append($"new {newType}();");
                        sbProperty.Append($"var n{index} = Math.Min(byteBuf.ReadSize(), byteBuf.Size);");
                        sbProperty.Append($"for (var i{index} = 0; i{index} < n{index}; i{index}++){{");
                        sbProperty.Append($"var key{index} = {PropertyDeserialize(keyType, $"key{index}",index+1)};");
                        sbProperty.Append($"var value{index} = {PropertyDeserialize(valueType, $"value{index}",index+1)};");
                        sbProperty.Append($"{propertyName}.Add(key{index}, value{index});}}");
                        return sbProperty.ToString();
                    }
                    if(type.StartsWith( SupportType.ValueTuple, StringComparison.OrdinalIgnoreCase))
                    {
                        var sb = new StringBuilder();
                        // Extract inner types from ValueTuple<T1,T2,...>
                        string innerTypesStr = type.Substring("ValueTuple<".Length, type.Length - "ValueTuple<".Length - 1);
                        string[] innerTypes = innerTypesStr.Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries);
                        List<string> elementReaders = new List<string>();

                        for (int i = 0; i < innerTypes.Length; i++)
                        {
                            string innerType = innerTypes[i].Trim();
                            // Read each tuple element using PropertyDeserialize with incremented index
                            elementReaders.Add(PropertyDeserialize(innerType, $"tupleItem{i}", index + 1));
                        }

                        // Create ValueTuple with all elements
                        sb.Append($"ValueTuple.Create({string.Join(", ", elementReaders)})");
                        return sb.ToString();
                    }
                }
                    return string.Empty;
            }
            return string.Empty;
        }

        /// <summary>
        /// peek 支持的类型 -> m_byteBuf 读取表达式。返回 null 表示该类型不支持 peek。
        /// 支持 int（含 LanguageType）；支持 string（共享 string 在 item 数据段存 int 索引，非共享存 string 本身）。
        /// 其他类型（long/bool/容器等）不支持 peek（返回 null，由校验拦截）。
        /// </summary>
        private string PeekReadExpr(string type, string propertyName)
        {
            if (string.IsNullOrEmpty(type)) return null;
            string lower = type.ToLower();
            bool isString = lower == SupportType.String.ToLower() || lower == SupportType.StringFull.ToLower();
            if (isString)
            {
                // 共享 string：item 数据段存 int 索引；非共享：存 string 本身
                return IsSharedCacheEnabled(propertyName)
                    ? "m_byteBuf.ReadInt()"
                    : "m_byteBuf.ReadString()";
            }
            if (lower == "int" || lower == SupportType.LanguageType.ToLower())
                return "m_byteBuf.ReadInt()";
            return null;
        }

        private bool HasCompoundIndex => _compoundIndexes != null && _compoundIndexes.Count > 0;

        /// <summary>
        /// 生成 ReadHead 内对每个组合索引的 BuildCompoundIndex 调用（须在 base.ReadHead 之后）。
        /// </summary>
        private string GenerateCompoundIndexBuildCalls()
        {
            if (_compoundIndexes == null || _compoundIndexes.Count == 0)
                return string.Empty;
            var sb = new StringBuilder();
            foreach (var ci in _compoundIndexes)
                sb.AppendLine($"\t\t\tBuildCompoundIndex_{ci.GroupName}();");
            return sb.ToString();
        }

        /// <summary>
        /// 为每个 CompoundIndex 生成：
        ///   1) 强类型映射字段 m_compoundIndex_{group}
        ///   2) BuildCompoundIndex_{group}（ReadHead 后调用，peek 填充，重复键抛错）
        ///   3) GetIdByCompoundKey_{group} / TryGetIdByCompoundKey_{group}
        /// 返回拼接代码（注入 ##CompoundIndexMembers##）；无组合索引返回空串。
        /// </summary>
        private string GenerateCompoundIndexCode()
        {
            if (_compoundIndexes == null || _compoundIndexes.Count == 0)
                return string.Empty;

            var fields = _configDataList?[0];
            if (fields == null || fields.Length == 0)
                return string.Empty;

            var sb = new StringBuilder();

            foreach (var ci in _compoundIndexes)
            {
                // 定位每个成员在字段序列的 index + 校验基础类型
                var memberPositions = new List<(int pos, string name, string type)>();
                foreach (var member in ci.Members)
                {
                    int pos = -1;
                    for (int i = 0; i < fields.Length; i++)
                    {
                        if (fields[i].Name == member.Name) { pos = i; break; }
                    }
                    if (pos < 0)
                        throw new InvalidOperationException($"[组合索引 {ci.GroupName}] 找不到字段 '{member.Name}'（表 {_className}）");
                    if (PeekReadExpr(fields[pos].Type, member.Name) == null)
                        throw new InvalidOperationException($"[组合索引 {ci.GroupName}] 字段 '{member.Name}' 类型 '{fields[pos].Type}' 不支持 peek（仅 int/string）");
                    memberPositions.Add((pos, member.Name, fields[pos].Type));
                }

                int maxPos = memberPositions.Max(m => m.pos);
                var memberPosSet = memberPositions.ToDictionary(m => m.pos);

                // 校验：[0..maxPos] 所有字段必须基础类型（peek 顺序读取，无法廉价 skip 容器）
                for (int i = 0; i <= maxPos; i++)
                {
                    if (PeekReadExpr(fields[i].Type, fields[i].Name) == null)
                        throw new InvalidOperationException($"[组合索引 {ci.GroupName}] 字段 '{fields[i].Name}'（类型 '{fields[i].Type}'）位于索引成员之前且非 int/string，无法 peek 跳过（表 {_className}）");
                }

                // 元组类型串 + 参数串（按成员在字段序列的出现顺序）
                var orderedMembers = memberPositions.OrderBy(m => m.pos).ToList();
                bool IsStringType(string t)
                {
                    string l = t.ToLower();
                    return l == SupportType.String.ToLower() || l == SupportType.StringFull.ToLower();
                }
                string CsType(string t) => IsStringType(t) ? "string" : "int";
                string tupleType = "(" + string.Join(", ", orderedMembers.Select(m => $"{CsType(m.type)} {m.name}")) + ")";
                string paramList = string.Join(", ", orderedMembers.Select(m => $"{CsType(m.type)} {m.name}"));
                string argList = string.Join(", ", orderedMembers.Select(m => m.name));

                // 1) 映射字段声明
                sb.AppendLine($"\t\tprivate Dictionary<{tupleType}, int> m_compoundIndex_{ci.GroupName};");

                // 2) BuildCompoundIndex_{group}：遍历 m_offsetMap，按顺序 peek [0..maxPos]
                sb.AppendLine($"\t\tprivate void BuildCompoundIndex_{ci.GroupName}()");
                sb.AppendLine("\t\t{");
                sb.AppendLine($"\t\t\tm_compoundIndex_{ci.GroupName} = new Dictionary<{tupleType}, int>(m_offsetMap.Count);");
                sb.AppendLine("\t\t\tforeach (var kv in m_offsetMap)");
                sb.AppendLine("\t\t\t{");
                sb.AppendLine("\t\t\t\tm_byteBuf.ReaderIndex = kv.Value;");
                for (int i = 0; i <= maxPos; i++)
                {
                    var f = fields[i];
                    bool isSharedString = IsStringType(f.Type) && IsSharedCacheEnabled(f.Name);
                    if (memberPosSet.ContainsKey(i) && isSharedString)
                    {
                        // 共享 string 成员：item 数据段存 int 索引，读索引后查 SharedCache 拿 string（复用共享实例）
                        // 注意：v2「槽0空值」布局下空引用索引为 0，会正常命中 cache[0]（空串）不再抛异常——语义见 w4 方案文档风险 R8；当前无表启用该路径。
                        sb.AppendLine($"\t\t\t\tint {f.Name}_idx = m_byteBuf.ReadInt();");
                        sb.AppendLine($"\t\t\t\tif (!_{f.Name.ToLower()}SharedCache.TryGetValue({f.Name}_idx, out string {f.Name}))");
                        sb.AppendLine($"\t\t\t\t\tthrow new InvalidOperationException($\"[组合索引 {ci.GroupName}] 共享缓存未命中: 字段 '{f.Name}', idx={{{f.Name}_idx}} (表 {_className})\");");
                    }
                    else if (memberPosSet.ContainsKey(i))
                    {
                        sb.AppendLine($"\t\t\t\t{CsType(f.Type)} {f.Name} = {PeekReadExpr(f.Type, f.Name)};");
                    }
                    else
                    {
                        sb.AppendLine($"\t\t\t\t{PeekReadExpr(f.Type, f.Name)}; // skip {f.Name}");
                    }
                }
                sb.AppendLine($"\t\t\t\tvar key = ({argList});");
                sb.AppendLine($"\t\t\t\tif (!m_compoundIndex_{ci.GroupName}.TryAdd(key, kv.Key))");
                sb.AppendLine($"\t\t\t\t\tthrow new InvalidOperationException($\"[组合索引 {ci.GroupName}] 重复的组合键: {{key}} (表 {_className})\");");
                sb.AppendLine("\t\t\t}");
                sb.AppendLine("\t\t}");

                // 3) GetIdByCompoundKey_{group}
                sb.AppendLine($"\t\tpublic int GetIdByCompoundKey_{ci.GroupName}({paramList})");
                sb.AppendLine("\t\t{");
                sb.AppendLine($"\t\t\treturn m_compoundIndex_{ci.GroupName}.TryGetValue(({argList}), out var id) ? id : 0;");
                sb.AppendLine("\t\t}");

                // 4) TryGetIdByCompoundKey_{group}
                sb.AppendLine($"\t\tpublic bool TryGetIdByCompoundKey_{ci.GroupName}({paramList}, out int id)");
                sb.AppendLine("\t\t{");
                sb.AppendLine($"\t\t\treturn m_compoundIndex_{ci.GroupName}.TryGetValue(({argList}), out id);");
                sb.AppendLine("\t\t}");

                // 5) 枚举所有组合键（供 Loader Init 遍历建轻量 id 映射，零 item 实例化）
                sb.AppendLine($"\t\tpublic IEnumerable<KeyValuePair<{tupleType}, int>> EnumerateCompoundIndex_{ci.GroupName}()");
                sb.AppendLine("\t\t{");
                sb.AppendLine($"\t\t\treturn m_compoundIndex_{ci.GroupName};");
                sb.AppendLine("\t\t}");
            }

            return sb.ToString();
        }

        private string GetContainerString(string type, string propertyName, bool container = false)
        {
            var sbProperty = new StringBuilder();

            // 检查该字段是否启用了共享缓存
            bool isSharedCacheEnabled = IsSharedCacheEnabled(propertyName);

            if (isSharedCacheEnabled)
            {
                // 共享缓存模式：只读取 index
                if (container) return string.Empty;
                sbProperty.Append($"\t\t\t_{propertyName.ToLower()}Index = byteBuf.ReadInt();\n");
                return sbProperty.ToString();
            }

            if (type.EndsWith(SupportType.Array,StringComparison.OrdinalIgnoreCase))
            {
                if (!container) return string.Empty;
                var innerType = type.Substring(0, type.Length - 2);
                sbProperty.Append($"\t\t\t{{var n = Math.Min(byteBuf.ReadSize(), byteBuf.Size);{propertyName}=new {innerType}[n]; for (var i = 0; i < n; i++){{{propertyName}[i]={PropertyDeserialize(innerType)};}}}}\n");
            }
            else if (type.StartsWith(SupportType.ValueTuple, StringComparison.OrdinalIgnoreCase) && type.EndsWith(">"))
            {
                if (!container) return string.Empty;
                // Extract inner types from ValueTuple<T1,T2,...>
                string innerTypeStr = type.Substring(SupportType.ValueTuple.Length, type.Length - SupportType.ValueTuple.Length - 1);
                string[] innerTypes = innerTypeStr.Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries);
                string newType = ReadExcel.GetTrueType(type);
                List<string> elementVariables = new List<string>();

                // Read each tuple element
                for (int i = 0; i < innerTypes.Length; i++)
                {
                    string innerType = innerTypes[i].Trim();
                    string elementVar = $"{propertyName}_tupleItem{i}";
                    elementVariables.Add(elementVar);
                    sbProperty.AppendLine($"\t\t\tvar {elementVar} = {PropertyDeserialize(innerType, elementVar, i)};");
                }

                // Create the ValueTuple with all elements
                string elements = string.Join(", ", elementVariables);
                sbProperty.AppendLine($"\t\t\t{propertyName} = new {newType}({elements});");
            }
            else if (type.StartsWith(SupportType.List,StringComparison.OrdinalIgnoreCase) && type.EndsWith(">"))
            {
                if (!container) return string.Empty;
                sbProperty.Append($"\t\t\t{{{propertyName}={PropertyDeserialize(type, propertyName,1)}}}\n");
            }
            else if ((type.StartsWith(SupportType.Dictionary,StringComparison.OrdinalIgnoreCase) || type.StartsWith(SupportType.DictionaryFull,StringComparison.OrdinalIgnoreCase)) && type.EndsWith(">"))
            {
                if (!container) return string.Empty;
                sbProperty.Append($"\t\t\t{{{propertyName}={PropertyDeserialize(type, propertyName,1)}}}\n");
            }
            else if(string.Equals(type, SupportType.RewardObject, StringComparison.OrdinalIgnoreCase))
            {
                if (!container)return string.Empty;
                sbProperty.Append($"\t\t\t{propertyName} = new RewardObject(byteBuf);\n");
            }
            else if(string.Equals(type, SupportType.ConditionObject, StringComparison.OrdinalIgnoreCase))
            {
                if (!container)return string.Empty;
                sbProperty.Append($"\t\t\t{propertyName} = new ConditionObject(byteBuf);\n");
            }
            else if(string.Equals(type, SupportType.EffectCfgObject, StringComparison.OrdinalIgnoreCase))
            {
                if (!container)return string.Empty;
                sbProperty.Append($"\t\t\t{propertyName} = new EffectCfgObject(byteBuf);\n");
            }
            else if(string.Equals(type, SupportType.GradedPriceObject, StringComparison.OrdinalIgnoreCase))
            {
                if (!container)return string.Empty;
                sbProperty.Append($"\t\t\t{propertyName} = new GradedPriceObject(byteBuf);\n");
            }
            else if(string.Equals(type, SupportType.LanguageType, StringComparison.OrdinalIgnoreCase))
            {
                if (container)return string.Empty;
                sbProperty.Append($"\t\t\tm_{propertyName.ToLower()} = {PropertyDeserialize(type)};\n");
            }
            else
            {
                if (container)return string.Empty;
                sbProperty.Append($"\t\t\t{propertyName} = {PropertyDeserialize(type)};\n");
            }
            return sbProperty.ToString();
        }

        /// <summary>
        /// 检查该字段是否启用了共享缓存
        /// </summary>
        private bool IsSharedCacheEnabled(string propertyName)
        {
            if (!_sharedCacheEnabled)
                return false;

            if (_sharedCacheInfos == null)
                return false;

            var cacheInfo = _sharedCacheInfos.FirstOrDefault(f => f.FieldName == propertyName && f.EnableSharedCache);
            return cacheInfo != null && cacheInfo.EnableSharedCache;
        }

        private string PropertyString(string type, string propertyName)
        {
            if (string.IsNullOrEmpty(type) || string.IsNullOrEmpty(propertyName))
                return null;

            _enumSource.Append(PropertyEnum(type, _className, _inputPath));

            // 检查是否启用共享缓存（复用 IsSharedCacheEnabled，使 _sharedCacheEnabled 开关生效）
            bool enableSharedCache = IsSharedCacheEnabled(propertyName);

            var newType = ReadExcel.GetTrueType(type, _className, _inputPath);
            if (!string.IsNullOrEmpty(newType))
            {
                StringBuilder sbProperty = new StringBuilder();

                if (string.Equals(type, SupportType.LanguageType, StringComparison.OrdinalIgnoreCase))
                {
                    // 多语言已经优化过，不需要重复优化
                    sbProperty.Append("\t\tprivate int " + "m_"+propertyName.ToLower() + ";\n");
                    sbProperty.Append("\t\tpublic int " + propertyName + "Key =>m_"+propertyName.ToLower() + ";\n");
                    sbProperty.Append("\t\tpublic " + newType + " " + propertyName + " => ConfigSystem.Instance.GetLanguageString(m_"+ propertyName.ToLower() +");\n");
                }
                else if (enableSharedCache)
                {
                    // 启用共享缓存，生成索引字段 + 属性访问
                    string actualTypeName = ReadExcel.GetTrueType(type);
                    string fieldNameLower = propertyName.ToLower();

                    // 生成静态空实例（用于 index = -1）
                    // 注意：下方发射的 `_xxxIndex < 0` 分支是 v1 布局（空引用 -1）的兼容路径。
                    // v2「槽0空值」布局下这个分支不会被走到（空引用写 0 命中 cache[0]），
                    // 但必须永久保留：玩家本地缓存、服务端副本、局部导出的表仍可能是 v1。不要当作死代码清理。
                    if (string.Equals(type, SupportType.RewardObject, StringComparison.OrdinalIgnoreCase) ||
                        string.Equals(type, SupportType.ConditionObject, StringComparison.OrdinalIgnoreCase) ||
                        string.Equals(type, SupportType.EffectCfgObject, StringComparison.OrdinalIgnoreCase) ||
                        string.Equals(type, SupportType.GradedPriceObject, StringComparison.OrdinalIgnoreCase))
                    {
                        // 自定义对象：添加静态空实例，所有 -1 都指向同一个空实例
                        sbProperty.Append($"\t\tprivate int _{fieldNameLower}Index;\n");
                        sbProperty.Append($"\t\tprivate static readonly {actualTypeName} _{fieldNameLower}Empty = new {actualTypeName}();\n");
                        sbProperty.Append($"\t\tpublic {actualTypeName} {propertyName} => _{fieldNameLower}Index < 0 ? _{fieldNameLower}Empty : {_className}Config._{fieldNameLower}SharedCache[_{fieldNameLower}Index];\n");
                    }
                    else if (type.Equals(SupportType.String, StringComparison.OrdinalIgnoreCase) ||
                             type.Equals(SupportType.StringFull, StringComparison.OrdinalIgnoreCase))
                    {
                        // string：空数据返回 string.Empty 而不是 null
                        sbProperty.Append($"\t\tprivate int _{fieldNameLower}Index;\n");
                        sbProperty.Append($"\t\tpublic {newType} {propertyName} => _{fieldNameLower}Index < 0 ? string.Empty : {_className}Config._{fieldNameLower}SharedCache[_{fieldNameLower}Index];\n");
                    }
                    else if (type.StartsWith(SupportType.List, StringComparison.OrdinalIgnoreCase))
                    {
                        // List<T>：空数据返回 new 空集合而不是 null
                        sbProperty.Append($"\t\tprivate int _{fieldNameLower}Index;\n");
                        sbProperty.Append($"\t\tprivate static readonly {actualTypeName} _{fieldNameLower}Empty = new {actualTypeName}();\n");
                        sbProperty.Append($"\t\tpublic {actualTypeName} {propertyName} => _{fieldNameLower}Index < 0 ? _{fieldNameLower}Empty : {_className}Config._{fieldNameLower}SharedCache[_{fieldNameLower}Index];\n");
                    }
                    else if (type.StartsWith(SupportType.Dictionary, StringComparison.OrdinalIgnoreCase) ||
                             type.StartsWith(SupportType.DictionaryFull, StringComparison.OrdinalIgnoreCase))
                    {
                        // Dictionary<TKey, TValue>：空数据返回 new 空字典而不是 null
                        sbProperty.Append($"\t\tprivate int _{fieldNameLower}Index;\n");
                        sbProperty.Append($"\t\tprivate static readonly {actualTypeName} _{fieldNameLower}Empty = new {actualTypeName}();\n");
                        sbProperty.Append($"\t\tpublic {actualTypeName} {propertyName} => _{fieldNameLower}Index < 0 ? _{fieldNameLower}Empty : {_className}Config._{fieldNameLower}SharedCache[_{fieldNameLower}Index];\n");
                    }
                    else
                    {
                        // 其他值类型保持 default
                        sbProperty.Append($"\t\tprivate int _{fieldNameLower}Index;\n");
                        sbProperty.Append($"\t\tpublic {newType} {propertyName} => _{fieldNameLower}Index < 0 ? default({newType}) : {_className}Config._{fieldNameLower}SharedCache[_{fieldNameLower}Index];\n");
                    }
                }
                else if(string.Equals(type, SupportType.RewardObject, StringComparison.OrdinalIgnoreCase))
                {
                    sbProperty.Append("\t\tpublic RewardObject " + propertyName + ";\n");
                }
                else if(string.Equals(type, SupportType.ConditionObject, StringComparison.OrdinalIgnoreCase))
                {
                    sbProperty.Append("\t\tpublic ConditionObject " + propertyName + ";\n");
                }
                else if(string.Equals(type, SupportType.EffectCfgObject, StringComparison.OrdinalIgnoreCase))
                {
                    sbProperty.Append("\t\tpublic EffectCfgObject " + propertyName + ";\n");
                }
                else if(string.Equals(type, SupportType.GradedPriceObject, StringComparison.OrdinalIgnoreCase))
                {
                    sbProperty.Append("\t\tpublic GradedPriceObject " + propertyName + ";\n");
                }
                else
                {
                    //sbProperty.Append("\t\t[Preserve]\n");
                    sbProperty.Append("\t\tpublic " + newType + " " + propertyName + " { get; private set; }\n");
                }
                return sbProperty.ToString();
            }
            else
            {
                return "";
            }
        }

        private string PropertyEnum(string type, string className = "", string inputPath = "", bool writtenForm = true)
        {
            if (!type.StartsWith(SupportType.Enum))
                return "";

            // 1. 检查是否有大括号（完整定义）或只有尖括号（简化定义）
            bool hasBraces = type.Contains('{') && type.Contains('}');
            string enumDefinition;
            string enumValues = "";

            if (hasBraces)
            {
                // 完整定义：enum<...>{...}
                int startBrace = type.IndexOf('{');
                int endBrace = type.LastIndexOf('}');

                if (startBrace == -1 || endBrace == -1)
                {
                    throw new ValidationException("枚举定义缺少大括号");
                }

                enumDefinition = type.Substring(SupportType.Enum.Length, startBrace - SupportType.Enum.Length)
                    .Trim('<', '>', ' ');
                enumValues = type.Substring(startBrace + 1, endBrace - startBrace - 1).Trim();
            }
            else
            {
                // 简化定义：enum<...>
                int startAngle = type.IndexOf('<');
                int endAngle = type.LastIndexOf('>');

                if (startAngle == -1 || endAngle == -1)
                {
                    throw new ValidationException("枚举定义缺少尖括号");
                }

                enumDefinition = type.Substring(startAngle + 1, endAngle - startAngle - 1).Trim();
            }

            // 2. 分割参数
            string[] enumParams = enumDefinition.Split(',');
            if (enumParams.Length < 1)
            {
                throw new ValidationException("枚举定义至少需要包含枚举名称");
            }

            string enumName = enumParams[0].Trim();

            // 3. 检查类名前缀（如果包含点）
            if (enumName.Contains('.'))
            {
                string[] parts = enumName.Split('.');
                if (parts[0] != className)
                {
                    return "";
                }
            }

            // 4. 设置默认值
            string underlyingType = enumParams.Length > 1 ? enumParams[1].Trim() : "int"; // 默认为int
            bool isFlags = enumParams.Length > 2 &&
                           enumParams[2].Trim().Equals("Flags", StringComparison.OrdinalIgnoreCase);

            // 5. 生成C#枚举代码
            var sb = new StringBuilder();

            if (isFlags)
            {
                sb.AppendLine("\t\t[System.Flags]");
            }

            sb.AppendLine("\t[Preserve]");

            sb.Append("\t\tpublic enum ").Append(enumName).Append(" : ").Append(ReadExcel.GetTrueType(underlyingType, className, inputPath, writtenForm)) .AppendLine();
            sb.AppendLine("\t\t{");

            // 6. 处理枚举值（如果有）
            if (hasBraces && !string.IsNullOrEmpty(enumValues))
            {
                string[] valuePairs = enumValues.Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries);
                foreach (string pair in valuePairs)
                {
                    string trimmedPair = pair.Trim();
                    if (!string.IsNullOrEmpty(trimmedPair))
                    {
                        sb.AppendLine("\t\t\t" + trimmedPair + ",");
                    }
                }
            }
            else
            {
                // 简化定义时添加一个默认值
                sb.AppendLine("\t\t\tNone = 0,");
            }

            sb.AppendLine("\t\t}");

            return sb.ToString();
        }

