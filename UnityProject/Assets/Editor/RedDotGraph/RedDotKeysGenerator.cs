#if UNITY_EDITOR
using System.Collections.Generic;
using System.Text;
using RedDot.Runtime.RedDot;
using TEngine;
using UnityEditor;
using UnityEngine;

namespace RedDot.Editor
{
    /// <summary>
    /// P0-5:key 常量表生成器。导出红点图 JSON 时同步产出 RedDotKeys.cs(Runtime/RedDot/)——
    /// 每个图节点一个 RedDotKey 常量(key+externalId 元数据),All 数组供加载期一致性自检对账。
    /// 拍板记录(2026-09-13):①形态=平铺常量(图 key 无层级结构,嵌套形态待 key 命名规范后由 P1-4 再议);
    /// ②成员名=key 派生合法 C# 标识符(非法字符→'_',数字开头→'N' 前缀,重名→"_2"后缀),排序按成员名
    /// Ordinal 保 diff 稳定;③挂点=ExportTo 自动+手动菜单(选导出 JSON 复跑);④externalId 分配工具化不做
    /// (编辑器 funcId 下拉已覆盖)。生成物为全量覆盖写,内容只依赖导出 JSON,幂等。
    /// </summary>
    public static class RedDotKeysGenerator
    {
        /// <summary>生成物落点(热更域 GameLogic 程序集内,业务可引用)。
        /// 2026-09-13 勘误:原常量少写一级 RedDot 目录,首次真跑把生成物写到 Runtime 根撞出 CS0101 重复定义。</summary>
        public const string OutputPath = "Assets/GameScripts/HotFix/GameLogic/Module/RedDotGraph/Runtime/RedDot/RedDotKeys.cs";

        /// <summary>手动重生成入口:选一份导出 JSON(导出链自动化之外的重跑/CI 通路)</summary>
        [MenuItem("Tools/红点系统/生成Key常量表(选导出JSON)")]
        public static void GenerateFromExportJsonFile()
        {
            var path = EditorUtility.OpenFilePanel("选择红点图导出 JSON", "Assets", "json");
            if (string.IsNullOrEmpty(path))
            {
                return;
            }
            var cfg = JsonUtility.FromJson<RedDotExportJson>(System.IO.File.ReadAllText(path, Encoding.UTF8));
            if (cfg == null || cfg.vertexs == null)
            {
                Log.Error("RedDotKeys 生成失败:JSON 解析为空,{0}", path);
                return;
            }
            WriteKeysFile(cfg);
        }

        /// <summary>导出链钩子(RedDotGraphData.ExportTo 调用):随导出自动再生成</summary>
        public static void GenerateFromExportJson(RedDotExportJson config)
        {
            WriteKeysFile(config);
        }

        /// <summary>产出常量表文件内容(纯函数,U6 验证器直测)。同 key 多顶点取首个并报错(加载期重复顶点本会失败)。
        /// 排序口径=派生成员名 Ordinal(保跨机 diff 稳定;按 key 排序在数字开头 key 加 N 前缀后与成员序漂移)。</summary>
        internal static string BuildFileContent(RedDotExportJson config)
        {
            //key→externalId 去重收集(先到先得);desc 旁表随行(K批8:中文描述写进便捷常量注释)
            var byKey = new Dictionary<string, RedDotKey>();
            var descByKey = new Dictionary<string, string>();
            if (config?.vertexs != null)
            {
                foreach (var vertex in config.vertexs)
                {
                    if (vertex == null || string.IsNullOrEmpty(vertex.key))
                    {
                        Log.Error("RedDotKeys 生成跳过空 key 顶点(externalId:{0})", vertex?.externalId ?? -1);
                        continue;
                    }
                    if (byKey.ContainsKey(vertex.key))
                    {
                        Log.Error("RedDotKeys 生成:重复 key {0}(externalId {1} 与 {2} 冲突,取首个)——重复顶点在加载期会被拒绝",
                            vertex.key, byKey[vertex.key].ExternalId, vertex.externalId);
                        continue;
                    }
                    byKey.Add(vertex.key, new RedDotKey(vertex.key, vertex.externalId));
                    descByKey[vertex.key] = vertex.desc ?? "";
                }
            }

            //派生成员名并按成员名 Ordinal 排序(All 数组与便捷字段同序,diff 稳定)
            var usedNames = new HashSet<string>();
            var entries = new List<KeyValuePair<string, string>>(byKey.Count); //key → memberName
            foreach (var kv in byKey)
            {
                entries.Add(new KeyValuePair<string, string>(kv.Key, DeriveMemberName(kv.Key, usedNames)));
            }
            entries.Sort((a, b) => string.CompareOrdinal(a.Value, b.Value));

            var sb = new StringBuilder(4096);
            sb.Append("// ------------------------------------------------------------------------------\n");
            sb.Append("// <auto-generated>\n");
            sb.Append("// 本文件由 RedDotKeysGenerator 在编辑器导出红点图时同步产出——禁止手改。\n");
            sb.Append("// 重新生成:红点图编辑器窗口 Export,或菜单 Tools/红点系统/生成Key常量表(选导出JSON)。\n");
            if (byKey.Count == 0)
            {
                sb.Append("// 当前内容:空表(红点图尚未导出过)。\n");
            }
            sb.Append("// </auto-generated>\n");
            sb.Append("// ------------------------------------------------------------------------------\n");
            sb.Append("namespace RedDot.Runtime.RedDot\n{\n");
            sb.Append("    /// <summary>\n");
            sb.Append("    /// P0-5 红点 key 常量表(生成物):当前红点图全部节点的 key 与 externalId 元数据。\n");
            sb.Append("    /// 业务经 RegisterChecker(RedDotKeys.XXX, checker) 注册、DataChange(RedDotKeys.XXX) 报脏。\n");
            sb.Append("    /// 加载期一致性自检以 All 为对账源——JSON(热更)与本表(热更 dll)版本错配在启动时即报。\n");
            sb.Append("    /// </summary>\n");
            sb.Append("    public static class RedDotKeys\n    {\n");
            sb.Append("        /// <summary>全量常量(对账源)。空表=红点图尚未导出,自检自动跳过。</summary>\n");
            sb.Append("        public static readonly RedDotKey[] All = new RedDotKey[]\n        {\n");
            foreach (var entry in entries)
            {
                sb.Append("            new RedDotKey(\"").Append(Escape(entry.Key)).Append("\", ").Append(byKey[entry.Key].ExternalId).Append("),\n");
            }
            sb.Append("        };\n");
            if (entries.Count > 0)
            {
                sb.Append("\n        // 便捷引用(按成员名 Ordinal 排序)\n");
            }
            foreach (var entry in entries)
            {
                var dk = byKey[entry.Key];
                //K批8:注释带出 key 字典中文描述(desc 随导出 JSON 流转,业务注册 checker 免回编辑器查语义)
                descByKey.TryGetValue(entry.Key, out var descText);
                var descSuffix = string.IsNullOrEmpty(descText) ? "" : "；" + descText;
                var summary = dk.ExternalId == -1
                    ? Utility.Text.Format("        /// <summary>{0} —— externalId:-1 聚合节点(无 checker,不可注册){1}</summary>\n", entry.Key, descSuffix)
                    : Utility.Text.Format("        /// <summary>{0} —— externalId:{1}{2}</summary>\n", entry.Key, dk.ExternalId, descSuffix);
                sb.Append(summary);
                sb.Append("        public static readonly RedDotKey ").Append(entry.Value)
                  .Append(" = new RedDotKey(\"").Append(Escape(entry.Key)).Append("\", ")
                  .Append(dk.ExternalId).Append(");\n");
            }
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        /// <summary>key → 合法 C# 标识符:非法字符→'_',数字开头→'N' 前缀,冲突→"_2"序号后缀</summary>
        internal static string DeriveMemberName(string key, HashSet<string> usedNames)
        {
            var sb = new StringBuilder(key.Length + 2);
            foreach (var c in key)
            {
                sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            }
            var name = sb.ToString();
            if (name.Length == 0 || char.IsDigit(name[0]))
            {
                name = "N" + name;
            }
            var final = name;
            int suffix = 2;
            while (!usedNames.Add(final))
            {
                final = name + "_" + suffix;
                suffix++;
            }
            return final;
        }

        private static string Escape(string key)
        {
            return key.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

        private static void WriteKeysFile(RedDotExportJson config)
        {
            var content = BuildFileContent(config);
            System.IO.File.WriteAllText(OutputPath, content, new UTF8Encoding(false));
            AssetDatabase.Refresh();
            Log.Info("RedDotKeys 常量表已生成:{0}(节点数见文件内 All 数组)", OutputPath);
        }
    }
}
#endif
